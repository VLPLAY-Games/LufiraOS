#pragma once

// dynlink.c — динамическая линковка (v0.8-мост, пункт 8, "полноценная", в
// явно ограниченном, но настоящем смысле: реальные .so, реальный PT_DYNAMIC,
// реальные GOT/PLT-релокации, реальное разделение физических страниц кода
// между процессами).
//
// АРХИТЕКТУРНОЕ РЕШЕНИЕ (принято здесь, не обсуждалось отдельно — см.
// объяснение в чате): классическая lazy-binding схема (PLT0 + runtime-
// резолвер, вызываемый ПРИ ПЕРВОМ обращении к каждому символу) требует
// отдельного процесса-интерпретатора (ld.so) и ассемблерного трамплина,
// сохраняющего/восстанавливающего регистры вокруг вызова резолвера —
// второй подвижный узел, которому сегодня здесь нет причины появляться.
// Вместо этого: EAGER-резолвинг прямо в ядре, в момент exec() (здесь же,
// elf_load_to_process() уже замаппил и скопировал все PT_LOAD-сегменты
// исполняемого файла — GOT-слоты реально существуют в памяти процесса и
// доступны для записи). Стандартные PLT-заглушки, которые gcc/ld кладёт
// в .plt.sec (endbr64; jmp *GOT_слот), от этого не меняются и не
// требуют резолвера: если GOT уже содержит финальный адрес ДО первого
// вызова, заглушка просто прыгает туда напрямую — реальный ELF ABI
// совместим с этим способом заполнения GOT, резолвер нужен только когда
// GOT изначально указывает обратно на сам PLT0 (lazy-путь, который мы не
// используем).
//
// Сами исполняемые файлы (пакеты) остаются ET_EXEC с фиксированным
// базовым адресом (как сегодня, БЕЗ изменений в их собственной загрузке)
// — им не нужна позиционная независимость, только настоящая libc.so
// (ET_DYN/PIC) — ОДИН раз загружается в ядре при первом использовании и
// кэшируется НАВСЕГДА (переживает все процессы): её ТЕКСТОВЫЕ страницы
// (PF_X и/или просто !PF_W — то есть и .rodata тоже) физически ОДНИ И ТЕ
// ЖЕ для каждого процесса, замаплены по ОДНОМУ и тому же фиксированному
// VA (DYNLINK_LIBC_BASE) в каждом адресном пространстве — экономия
// памяти, которая и есть смысл "полноценной" динамической линковки, а не
// просто "линковка в момент запуска, а не в момент сборки". ДАННЫЕ/BSS
// (PF_W) — наоборот, свежая приватная копия на каждый процесс (у malloc()
// внутри libc.so своё собственное состояние кучи на процесс — без этого
// два процесса делили бы один malloc()-heap, что неверно).
//
// Общие текстовые страницы учитываются через уже существующий реестр
// shm.c (v0.8-мост, пункт 4) — PAGE_MMAP_SHARED + shm_create()/
// shm_add_ref()/shm_release() с тем же постраничным refcount, что уже
// умеют unmap_page()/free_user_address_space() (paging.c) и
// clone_address_space_deep() (process.c, для fork()) — ни одна из них не
// нуждается в изменениях: они не знают и не должны знать, что эта
// конкретная shared-область — общая libc.so, а не пользовательский
// MAP_SHARED mmap().

#include "lib/types.h"
#include "elf.h"

typedef struct process process_t;

// Фиксированный VA, по которому libc.so замаплена ОДИНАКОВО в КАЖДОМ
// процессе — тот же приём, что уже применяется для
// SIGNAL_STACK_AREA_START/MMAP_AREA_START (process.h): разные процессы
// имеют разные таблицы страниц, так что коллизии между процессами нет, а
// одинаковый VA означает, что релокации САМОЙ libc.so (R_X86_64_RELATIVE)
// обрабатываются ОДИН раз при первой загрузке, не для каждого процесса
// заново.
#define DYNLINK_LIBC_BASE 0x0000580000000000ULL

// Если исполняемый файл elf_data содержит PT_DYNAMIC с DT_NEEDED — грузит
// (при первом обращении — кэширует навсегда) /lib/libc.so, маппит её
// текстовые страницы (общие, см. выше) и свежую приватную копию
// данных/bss в адресное пространство proc, затем обрабатывает
// релокации .rela.plt/.rela.dyn исполняемого файла (R_X86_64_JUMP_SLOT/
// GLOB_DAT/COPY), записывая финальные адреса символов libc.so прямо в
// уже замапленную память proc.
//
// ОБЯЗАТЕЛЬНО звать ПОСЛЕ того, как elf_load_to_process() уже замаппил,
// скопировал содержимое и выставил финальные права доступа на ВСЕ
// PT_LOAD-сегменты исполняемого файла elf_data — релокации пишут прямо в
// эту память, она должна быть И присутствовать, И доступна на запись
// (сам GOT лежит в .data/.got.plt, уже PAGE_WRITE к этому моменту).
//
// Возвращает 0, если PT_DYNAMIC отсутствует вовсе (обычный статический
// бинарник — полная обратная совместимость с этапами 1-7) ИЛИ линковка
// прошла успешно; -1 при реальной ошибке (нет /lib/libc.so на диске,
// неизвестный DT_NEEDED, не найден нужный символ, повреждённые
// релокации).
int dynlink_process(process_t *proc, const void *elf_data,
                     const elf64_program_header_t *ph, int phnum);
