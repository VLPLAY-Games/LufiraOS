#pragma once

// dynlink.c — динамическая линковка (v0.8-мост, пункт 8): реальные .so,
// PT_DYNAMIC, GOT/PLT-релокации, разделение физических страниц кода между
// процессами.
//
// Архитектурное решение: вместо классической lazy-binding схемы (PLT0 +
// runtime-резолвер при первом обращении к символу, требующий отдельного
// ld.so и асм-трамплина) — EAGER-резолвинг прямо в ядре при exec(), когда
// elf_load_to_process() уже замаппил все PT_LOAD-сегменты и GOT-слоты
// доступны для записи. Стандартные PLT-заглушки gcc/ld в .plt.sec (endbr64;
// jmp *GOT-слот) от этого не меняются: если GOT уже содержит финальный
// адрес до первого вызова, заглушка просто прыгает туда — ABI совместим,
// резолвер нужен только для lazy-пути, который здесь не используется.
//
// Исполняемые файлы остаются ET_EXEC с фиксированной базой (без изменений
// в их загрузке) — позиционная независимость нужна только libc.so
// (ET_DYN/PIC): грузится в ядре один раз и кэшируется навсегда. Её
// текстовые страницы (PF_X и/или !PF_W, т.е. и .rodata) физически ОДНИ И ТЕ
// ЖЕ для каждого процесса, по одному и тому же VA (DYNLINK_LIBC_BASE) — в
// этом и есть экономия памяти настоящей динамической линковки. ДАННЫЕ/BSS
// (PF_W) — наоборот, свежая приватная копия на процесс (иначе malloc()
// внутри libc.so делил бы один heap между процессами).
//
// Общие текстовые страницы учитываются через существующий реестр shm.c:
// PAGE_MMAP_SHARED + shm_create()/shm_add_ref()/shm_release() с тем же
// постраничным refcount, что уже умеют unmap_page()/free_user_address_space()
// и clone_address_space_deep() — им не нужно знать, что эта shared-область
// — libc.so, а не обычный MAP_SHARED mmap().

#include "lib/types.h"
#include "elf.h"

typedef struct process process_t;

// Фиксированный VA, по которому libc.so замаплена ОДИНАКОВО в КАЖДОМ
// процессе — тот же приём, что уже применяется для
// SIGNAL_STACK_AREA_START/MMAP_AREA_START (process.h): разные процессы
// имеют разные таблицы страниц, так что коллизии между процессами нет, а
// одинаковый VA означает, что релокации САМОЙ libc.so (R_X86_64_RELATIVE)
// обрабатываются ОДИН раз при первой загрузке, не для каждого процесса
// заново.
#define DYNLINK_LIBC_BASE 0x0000580000000000ULL

// Если elf_data содержит PT_DYNAMIC с DT_NEEDED — грузит (кэширует навсегда
// при первом обращении) /lib/libc.so, маппит её текстовые страницы (общие,
// см. выше) и свежую приватную копию данных/bss в proc, затем обрабатывает
// релокации .rela.plt/.rela.dyn (R_X86_64_JUMP_SLOT/GLOB_DAT/COPY), записывая
// финальные адреса символов libc.so прямо в уже замапленную память proc.
//
// ОБЯЗАТЕЛЬНО звать ПОСЛЕ того, как elf_load_to_process() замаппил,
// скопировал содержимое и выставил финальные права на ВСЕ PT_LOAD-сегменты
// elf_data — релокации пишут прямо в эту память (GOT лежит в .data/.got.plt,
// уже PAGE_WRITE к этому моменту).
//
// Возвращает 0, если PT_DYNAMIC отсутствует (обычный статический бинарник)
// ИЛИ линковка прошла успешно; -1 при ошибке (нет /lib/libc.so, неизвестный
// DT_NEEDED, не найден символ, повреждённые релокации).
int dynlink_process(process_t *proc, const void *elf_data,
                     const elf64_program_header_t *ph, int phnum);
