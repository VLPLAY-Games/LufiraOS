#pragma once

#include "lib/types.h"

/*
 * Минимальный блокирующий TCP-клиент — ОДНО соединение единовременно, БЕЗ
 * congestion control, приём только "по порядку" (внеочередной сегмент не
 * берётся — нет буфера пересборки — но, в отличие от более ранней версии
 * этого файла, ACK'ается немедленно, чтобы собеседник понял, откуда
 * повторять, см. tcp_receive()). Ретрансмиссия ПО ТАЙМЕРУ у исходящих
 * данных (stop-and-wait, см. tcp_retransmit_if_needed() ниже) есть и
 * реально используется. Приёмное окно (tcp_rx_window()) теперь настоящее,
 * не константа — собеседник сам не шлёт больше, чем помещается в
 * rx_fifo/кольцо RTL8139, так что принятые данные при обычной работе
 * сети не теряются (см. "НАЙДЕННЫЙ БАГ" в начале tcp.c — до этого
 * терялось ВСЁ, кроме первого сегмента в каждой подряд идущей пачке).
 */

#define TCP_FLAG_FIN 0x01u
#define TCP_FLAG_SYN 0x02u
#define TCP_FLAG_RST 0x04u
#define TCP_FLAG_PSH 0x08u
#define TCP_FLAG_ACK 0x10u

typedef struct __attribute__((packed)) {
    uint16_t src_port;
    uint16_t dst_port;
    uint32_t seq;
    uint32_t ack;
    uint8_t  data_offset_reserved; // старшие 4 бита — длина заголовка в 32-битных словах
    uint8_t  flags;
    uint16_t window;
    uint16_t checksum;
    uint16_t urgent_ptr;
} tcp_header_t;

// Активное открытие: SYN -> ждёт SYN-ACK (ограниченный таймаут, ~3000мс) ->
// ACK. 0 = ESTABLISHED, -1 = таймаут/ошибка. Заменяет любое предыдущее
// соединение (единственное на весь стек, см. план).
int tcp_connect(uint32_t remote_ip, uint16_t remote_port);

// Отправляет data одним или несколькими PSH|ACK-сегментами (stop-and-wait
// с ретрансмиссией по таймеру на каждый, см. tcp_retransmit_if_needed() в
// tcp.c). 0 = успех, -1 = не ESTABLISHED/ошибка отправки.
int tcp_send(const void *data, uint16_t len);

// Опрашивает карту один раз. Если в очереди приёма есть непотреблённые
// байты — возвращает 1 и указатель/длину ОДНОГО куска, не больше ~1460
// байт (валидны до ближайшего tcp_ack_consumed(); повторный
// tcp_recv_poll() до него отдаёт ровно тот же кусок той же длины); иначе 0.
//
// Границы кусков с границами сегментов НЕ совпадают и совпадать не
// обязаны — это поток байт. Принятое по порядку копится в очереди
// (~8КБ) независимо от того, успел ли вызывающий её разобрать, а
// объявляемое собеседнику окно отражает реальный остаток места, так что
// переполнения очереди с потерей данных не бывает: отправитель просто
// приостанавливается до ближайшего tcp_ack_consumed(). Почему это важно
// и чем оборачивалось раньше — блок "НАЙДЕННЫЙ БАГ" в начале tcp.c.
int tcp_recv_poll(uint8_t **out_ptr, uint16_t *out_len);

// Освобождает последний отданный tcp_recv_poll() кусок и шлёт ACK с
// обновлённым окном. Вызывать ровно один раз после каждого успешного
// tcp_recv_poll(): пока он не вызван, очередь не сдвигается, и окно для
// собеседника не растёт.
void tcp_ack_consumed(void);

// 1, если удалённая сторона прислала FIN (данных больше не будет —
// вызывающей стороне пора завершать чтение и звать tcp_close()).
int tcp_is_remote_closed(void);

// FIN -> best-effort (ограниченный таймаут) ожидание закрытия с той
// стороны, затем локальное закрытие в любом случае (клиент, которому
// сокет больше не нужен, не обязан строго дожидаться graceful close).
void tcp_close(void);

// Вызывается из ip_receive() на TCP-сегменты, адресованные текущему
// соединению; остальное молча отбрасывается.
void tcp_receive(uint32_t src_ip, const void *payload, uint16_t len);
