#pragma once

#include "lib/types.h"

/*
 * Минимальный клиент TLS 1.2 поверх tcp.c — ровно столько, чтобы dlpg
 * sync/upgrade (-> SYS_NET_FETCH -> http_client.c) сходил по https:// на
 * raw.githubusercontent.com. Намеренно узкий срез протокола, не полная
 * реализация; границы объёма — в начале tls.c.
 *
 * Одно соединение единовременно (состояние статическое, как у tcp.c) —
 * tls_connect() неявно заменяет предыдущее.
 *
 * Про доверие, коротко (подробно — в начале tls.c и у SYS_NET_FETCH в
 * syscall.h): подпись ServerKeyExchange проверяется ключом ИЗ
 * ПРЕДЪЯВЛЕННОГО сертификата, но сам сертификат ни к какому корневому CA
 * не привязывается — доверенных корней в этой ОС нет. То есть "сервер
 * владеет ключом к показанному сертификату", а не "сервер — тот, кого
 * мы запрашивали".
 */

// Устанавливает TCP и проводит полное рукопожатие TLS 1.2, включая
// проверку подписи ServerKeyExchange. sni_hostname обязателен (уходит в
// расширение server_name) — без него GitHub/Fastly не выберут ни
// маршрут, ни сертификат.
//
// 0 = успех, -1 = любая неудача (TCP, таймаут, alert, cipher suite,
// сертификат, подпись, Finished) — без градации: вызывающему
// (http_client.c) всё это одинаково ETLS. При dev-режиме причина уходит
// в DLOG (см. tls.c).
int tls_connect(uint32_t ip, uint16_t port, const char *sni_hostname);

// Отправляет len байт прикладных данных (одной или несколькими
// зашифрованными записями). 0 = успех, -1 = ошибка/нет соединения.
int tls_send(const void *data, uint16_t len);

// "Короткое чтение", как у блокирующего сокета: >0 — байт реально
// положено в buf (может быть меньше maxlen), 0 — корректное закрытие
// (close_notify либо TCP FIN, данных больше нет), -1 — ошибка.
// Блокируется циклом до дедлайна по pit_get_ticks(), как
// tcp_connect()/dns_resolve().
int tls_recv(uint8_t *buf, uint16_t maxlen);

// Best-effort: пытается отправить alert close_notify, затем закрывает TCP
// через tcp_close() в любом случае. Безопасно вызывать и без соединения.
void tls_close(void);
