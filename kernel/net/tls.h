#pragma once

#include "lib/types.h"

/*
 * Минимальный клиент TLS 1.2 поверх tcp.c — ровно столько, сколько нужно,
 * чтобы пакетный менеджер (dlpg sync/upgrade -> SYS_NET_FETCH ->
 * http_client.c) сходил по https:// на raw.githubusercontent.com. Как и
 * весь остальной сетевой стек этой ОС (см. комментарии в tcp.c/dns.c), это
 * НЕ полноценная реализация протокола, а намеренно узкий срез; границы
 * объёма расписаны в начале tls.c.
 *
 * ОДНО соединение единовременно (всё состояние статическое, как у tcp.c) —
 * tls_connect() неявно заменяет предыдущее.
 *
 * ПРО ДОВЕРИЕ, коротко (подробно — в начале tls.c и у SYS_NET_FETCH в
 * kernel/system/syscall/syscall.h): подпись ServerKeyExchange проверяется
 * открытым ключом ИЗ ПРЕДЪЯВЛЕННОГО сервером сертификата, но сам
 * сертификат ни к какому корневому CA не привязывается — доверенного
 * набора корней в этой ОС нет. То есть "сервер владеет ключом к
 * сертификату, который показал", а не "сервер — это тот, кого мы
 * запрашивали".
 */

// Устанавливает TCP-соединение и проводит полное рукопожатие TLS 1.2,
// включая проверку подписи ServerKeyExchange. sni_hostname обязателен и
// уходит в расширение server_name — без него GitHub/Fastly не смогут
// выбрать ни маршрут, ни сертификат.
//
// 0 = успех, -1 = ЛЮБАЯ неудача: не поднялся TCP, таймаут, alert от
// сервера, выбран не тот cipher suite, не разобрался сертификат, не
// сошлась подпись, не сошёлся Finished. Более тонкой градации сознательно
// нет — вызывающему (http_client.c) всё это одинаково означает ETLS, а
// различать причины ему незачем; при включённом dev-режиме конкретная
// причина уходит в DLOG (см. tls.c).
int tls_connect(uint32_t ip, uint16_t port, const char *sni_hostname);

// Отправляет len байт прикладных данных (одной или несколькими
// зашифрованными записями). 0 = успех, -1 = ошибка/нет соединения.
int tls_send(const void *data, uint16_t len);

// Семантика "короткого чтения", как у блокирующего сокета: >0 — сколько
// байт реально положено в buf (может быть меньше maxlen), 0 — соединение
// корректно закрыто (пришёл close_notify либо TCP FIN, и расшифрованных
// данных больше не осталось), -1 — ошибка. Блокируется внутри по тому же
// принципу "цикл до дедлайна по pit_get_ticks()", что tcp_connect() и
// dns_resolve() — отдельной модели конкурентности тут не появляется.
int tls_recv(uint8_t *buf, uint16_t maxlen);

// Best-effort: пытается отправить alert close_notify, затем закрывает TCP
// через tcp_close() в любом случае. Безопасно вызывать и без соединения.
void tls_close(void);
