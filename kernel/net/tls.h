#pragma once

#include "lib/types.h"

/*
 * Минимальный клиент TLS 1.2 поверх tcp.c — ровно столько, чтобы dlpg
 * sync/upgrade сходил по https:// на raw.githubusercontent.com. Узкий
 * срез протокола, не полная реализация (границы объёма — в tls.c).
 *
 * Одно соединение единовременно (статическое состояние, как у tcp.c) —
 * tls_connect() неявно заменяет предыдущее.
 *
 * Доверие (подробно — в tls.c/syscall.h): подпись ServerKeyExchange
 * проверяется ключом из предъявленного сертификата, но сам сертификат
 * ни к какому CA не привязывается — "сервер владеет ключом к
 * показанному сертификату", а не "сервер — тот, кого мы запрашивали".
 */

// Устанавливает TCP и проводит рукопожатие TLS 1.2, включая проверку
// подписи ServerKeyExchange. sni_hostname обязателен (расширение
// server_name) — без него GitHub/Fastly не выберут маршрут/сертификат.
//
// 0 = успех, -1 = любая неудача (без градации — вызывающему всё одинаково
// ETLS; причина уходит в DLOG при dev-режиме).
int tls_connect(uint32_t ip, uint16_t port, const char *sni_hostname);

// Отправляет len байт прикладных данных (одной или несколькими
// зашифрованными записями). 0 = успех, -1 = ошибка/нет соединения.
int tls_send(const void *data, uint16_t len);

// "Короткое чтение": >0 — байт положено в buf (может быть меньше
// maxlen), 0 — корректное закрытие (close_notify/FIN), -1 — ошибка.
// Блокируется до дедлайна по pit_get_ticks(), как tcp_connect()/dns_resolve().
int tls_recv(uint8_t *buf, uint16_t maxlen);

// Best-effort: пытается отправить alert close_notify, затем закрывает TCP
// через tcp_close() в любом случае. Безопасно вызывать и без соединения.
void tls_close(void);
