#pragma once

#include "lib/types.h"

// Разрешает ip (host-order) в MAC-адрес: попадание в кэш — мгновенно;
// промах — рассылает ARP request и блокирующе (ограниченный таймаут,
// ~2000мс) ждёт ответа, опрашивая карту сама (та же схема, что и
// xhci_wait_for_event() у USB-стека). 0 = успех, -1 = таймаут.
int arp_resolve(uint32_t ip, uint8_t out_mac[6]);

// Вызывается из eth_receive() на ARP-кадры — отвечает на запросы к нашему
// IP и обучает кэш из любого увиденного запроса/ответа (оппортунистически,
// как это принято в большинстве минимальных ARP-реализаций).
void arp_receive(const uint8_t *payload, uint16_t len);
