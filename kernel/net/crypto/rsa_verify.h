#pragma once

#include "lib/types.h"

/*
 * Ровно две операции, нужные net/tls.c для аутентификации сервера:
 * вытащить открытый RSA-ключ из DER-сертификата X.509 и проверить им
 * подпись RSA PKCS#1 v1.5 с SHA-256 (подпись под ServerKeyExchange).
 *
 * ВАЖНО ПРО ОБЪЁМ. Это НЕ валидация сертификата. Здесь нет и не
 * предполагается: проверки цепочки до доверенного корневого CA (набора
 * корневых сертификатов в ОС вообще нет), проверки срока действия,
 * сверки CN/SubjectAltName с именем хоста, разбора расширений,
 * KeyUsage/BasicConstraints, CRL/OCSP. Разбор сертификата идёт ровно до
 * subjectPublicKeyInfo и останавливается — всё, что дальше и вокруг,
 * пропускается не читая. Что это даёт и чего НЕ даёт — подробно
 * расписано у SYS_NET_FETCH (kernel/system/syscall/syscall.h) и в
 * заголовке tls.c; коротко: доказывает, что собеседник владеет закрытым
 * ключом к предъявленному сертификату, но НЕ доказывает, что этот
 * сертификат принадлежит запрошенному хосту.
 *
 * Разбор DER ведётся ПО МЕСТУ — rsa_public_key_t хранит указатели внутрь
 * переданного буфера сертификата, ничего не копируя. Буфер обязан жить,
 * пока ключом пользуются (в tls.c это буфер сборки handshake-сообщения,
 * живущий до конца рукопожатия).
 */

typedef struct {
    const uint8_t *modulus;      // без ведущего нулевого байта DER INTEGER
    uint32_t       modulus_len;
    const uint8_t *exponent;
    uint32_t       exponent_len;
} rsa_public_key_t;

// Находит в DER-сертификате X.509 его subjectPublicKeyInfo и разбирает
// лежащий там RSAPublicKey SEQUENCE { INTEGER modulus, INTEGER
// publicExponent }. 0 = успех, -1 = не разобралось (битый DER, другая
// структура, не-RSA ключ — отличать эти случаи вызывающему незачем, любой
// из них одинаково означает "аутентифицировать сервер нечем").
int x509_extract_rsa_pubkey(const uint8_t *der, uint32_t der_len, rsa_public_key_t *out);

// Проверяет подпись RSA PKCS#1 v1.5 (RFC 8017 §8.2.2) над SHA-256(msg).
// 0 = подпись верна, -1 = не верна/не разобралась. Отказ ВСЕГДА означает
// "не аутентифицировано" — вызывающий обязан на нём обрывать соединение,
// а не продолжать (см. tls.c).
int rsa_pkcs1_sha256_verify(const rsa_public_key_t *key,
                            const uint8_t *sig, uint32_t sig_len,
                            const uint8_t *msg, uint32_t msg_len);
