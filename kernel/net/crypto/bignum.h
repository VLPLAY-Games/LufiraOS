#pragma once

#include "lib/types.h"

/*
 * Длинная беззнаковая арифметика ровно под ОДНУ задачу: modexp для
 * проверки подписи RSA PKCS#1 v1.5 (сертификат сервера -> подпись
 * ServerKeyExchange, см. net/tls.c). Ничего больше здесь не нужно — ни
 * деления, ни НОД, ни генерации ключей: мы только ПРОВЕРЯЕМ подпись
 * открытым ключом, свои RSA-ключи ядро не создаёт и не использует.
 *
 * Поэтому и реализация нарочито "школьная": modexp через возведение в
 * квадрат с умножением, а само модульное умножение — побитовым методом
 * "сдвиг-и-сложение" (r = 2r (mod n), при единичном бите r += a (mod n)).
 * Умножения длинных чисел и честного деления с остатком (алгоритм D
 * Кнута) здесь нет вообще — а это самая частая причина трудноуловимых
 * ошибок в самодельных bignum'ах. Цена — скорость, но проверка подписи
 * происходит РОВНО ОДИН РАЗ на TLS-рукопожатие, и показатель e у
 * настоящих сертификатов это 65537 (17 бит), то есть вся проверка это
 * ~18 модульных умножений.
 */

// 4096 бит — заведомо с запасом: сертификаты GitHub/Fastly почти наверняка
// RSA-2048, но упираться в потолок ровно на 2048 не хочется (встречаются и
// RSA-3072/4096, см. tls.c).
#define BIGNUM_MAX_BYTES 512

// out = (base ^ exp) mod mod. Все числа — массивы байт BIG-ENDIAN
// (именно в таком виде они лежат и в DER-сертификате, и в поле подписи
// TLS-записи, так что перекладывать ничего не надо). out получает ровно
// out_len байт, дополненных нулями слева.
//
// Возвращает 0 при успехе, -1 если: какая-то из длин больше
// BIGNUM_MAX_BYTES, out_len меньше значащей длины результата, или модуль
// равен нулю. base БОЛЬШЕ модуля ошибкой НЕ является — он просто
// приводится по модулю.
int bignum_modexp(uint8_t *out, size_t out_len,
                  const uint8_t *base, size_t base_len,
                  const uint8_t *exp, size_t exp_len,
                  const uint8_t *mod, size_t mod_len);
