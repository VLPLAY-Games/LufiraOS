#pragma once

#include "lib/types.h"

/*
 * Арифметика ровно под modexp для проверки подписи RSA PKCS#1 v1.5
 * (ServerKeyExchange, см. net/tls.c) — деление, НОД, генерация ключей не нужны.
 *
 * Реализация "школьная": возведение в квадрат с умножением, само умножение —
 * побитовое "сдвиг-и-сложение" (r=2r mod n, при бите r+=a mod n); честного
 * умножения длинных чисел и деления с остатком нет — частый источник ошибок
 * в самодельных bignum. Цена — скорость, но проверка идёт раз за рукопожатие,
 * а e сертификатов обычно 65537 (17 бит) — то есть ~18 умножений.
 */

// 4096 бит — с запасом: реальные сертификаты обычно RSA-2048, но встречаются
// и RSA-3072/4096 (см. tls.c).
#define BIGNUM_MAX_BYTES 512

// out = (base^exp) mod mod. Числа — BIG-ENDIAN байты (как в DER-сертификате
// и в поле подписи TLS, перекладывать не нужно). out получает ровно out_len
// байт, дополненных нулями слева.
//
// 0 при успехе; -1 если длина больше BIGNUM_MAX_BYTES, out_len меньше нужной
// длины результата, или модуль равен нулю. base > модуль — не ошибка, приводится.
int bignum_modexp(uint8_t *out, size_t out_len,
                  const uint8_t *base, size_t base_len,
                  const uint8_t *exp, size_t exp_len,
                  const uint8_t *mod, size_t mod_len);
