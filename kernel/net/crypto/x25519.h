#pragma once

#include "lib/types.h"

/*
 * X25519 (RFC 7748) — скалярное умножение на кривой Монтгомери Curve25519.
 * Единственная группа, которую наш TLS-клиент предлагает в расширении
 * supported_groups (named group 0x001D, см. net/tls.c): ECDHE целиком
 * сводится к двум вызовам отсюда — своя публичная точка от своего
 * секретного скаляра и общий секрет от секретного скаляра и присланной
 * сервером точки.
 *
 * Выбрана именно она, а не NIST P-256: у X25519 нет ни проверки
 * принадлежности точки кривой, ни разбора формата точки, ни инверсий по
 * модулю порядка группы — любые 32 байта являются корректным входом, что
 * убирает целый класс ошибок реализации. Арифметика — в 16 конечностях по
 * 16 бит на int64_t, без 128-битных типов (ядро собирается с
 * -mgeneral-regs-only, см. KERNEL_CFLAGS в Makefile).
 */

#define X25519_KEY_SIZE 32

// out = scalar * point. Все три буфера — 32 байта little-endian, как
// требует RFC 7748 §5. scalar приводится внутри (clamping: младшие 3 бита
// в 0, старший в 0, второй старший в 1), вызывающему это делать не нужно.
void x25519_scalarmult(uint8_t out[X25519_KEY_SIZE],
                       const uint8_t scalar[X25519_KEY_SIZE],
                       const uint8_t point[X25519_KEY_SIZE]);

// out = scalar * G, где G — стандартная базовая точка u = 9.
void x25519_base(uint8_t out[X25519_KEY_SIZE], const uint8_t scalar[X25519_KEY_SIZE]);
