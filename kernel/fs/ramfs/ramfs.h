#pragma once

#include "lib/types.h"

// RAMFS — v0.9, фаза 1, пункт 1: чисто оперативная файловая система,
// смонтированная по префиксу пути (та же модель, что vfs_fat_mount() —
// см. fat_mount.h), но БЕЗ ограничений FAT-монтирования: это не
// "весь образ устройства одним куском в RAM с капом 8 МБ", а обычное
// дерево узлов, растущее по требованию через kmalloc()/kfree(), и
// ВКЛЮЧАЯ вложенные каталоги произвольной глубины — FAT-монтирование
// сознательно ограничено только корневым уровнем (см. ГРАНИЦА в
// fat_mount.h), здесь такого ограничения в принципе нет, т.к. узлы ramfs
// образуют собственное дерево с родителем/детьми, а не живут поверх
// плоского by-value FAT-образа.
//
// Данные не переживают перезагрузку (не синкаются ни на какое
// устройство) — в этом смысле ближе к Linux tmpfs, чем к постоянному
// хранилищу. Подходит под /tmp и как общая песочница для будущих
// RAMFS-зависимых вещей (см. план v0.9: установщик 1.0 планирует live-
// окружение поверх RAMFS).

#define RAMFS_MAX_MOUNTS      4
#define RAMFS_MOUNT_PREFIX_MAX 32
#define RAMFS_MAX_NAME        64

struct inode;

// Монтирует новый, изначально пустой инстанс RAMFS по указанному
// абсолютному префиксу ("/tmp" и т.п.) — должен начинаться с '/' и не
// совпадать ни с одним уже смонтированным префиксом (FAT- или RAMFS-).
// 0 при успехе, иначе отрицательный код ошибки (см. .c, как у
// vfs_fat_mount()): -1 плохой prefix, -2 уже занято, -3 нет слотов,
// -4 kmalloc не удался.
int ramfs_mount(const char *prefix);

// Размонтирует и освобождает ВСЁ дерево узлов (данные теряются — ramfs
// никогда ничего никуда не синкает). 0 при успехе, -1 если такого
// монтирования нет.
int ramfs_unmount(const char *prefix);

int vfs_ramfs_mount_count(void);

// Та же -2 "path не под этим монтированием" конвенция, что у
// vfs_fat_open()/vfs_fat_mkdir()/... (vfs.c проверяет её и, если path не
// наш, просто идёт дальше к LufiraFS) — см. fat_mount.h.
int vfs_ramfs_open(const char *path, int flags);
int vfs_ramfs_mkdir(const char *path);
int vfs_ramfs_unlink(const char *path);
struct inode *vfs_ramfs_lookup(const char *path);
