#pragma once

#include "lib/types.h"

/*
 * Драйвер сетевой карты RTL8139 (Realtek, PCI vendor 0x10EC device 0x8139) —
 * классическая карта, использующая порт-I/O BAR0 (не MMIO) и НЕ
 * поддерживающая scatter-gather на приём: NIC пишет входящие кадры прямо в
 * один физически непрерывный кольцевой буфер (см. pmm_alloc_contiguous_pages()
 * в kernel/system/mm/pmm.c — единственный потребитель этой функции).
 *
 * Как и xHCI/AC'97 — прерывания контроллера не используются (в этом ядре
 * нет ни APIC/MSI, ни разбора PCI capability list). rtl8139_poll(),
 * вызываемая раз в тик PIT (100 Гц) из kernel/net/net.c:net_poll(), читает и
 * подтверждает биты ISR напрямую — они защёлкиваются аппаратно независимо
 * от IMR, который здесь всегда остаётся 0 (реальная линия INTx никогда не
 * взводится).
 */

// Инициализация: ищет контроллер через PCI, включает I/O + bus mastering,
// сбрасывает, настраивает приём/передачу, читает MAC-адрес. Безопасно
// вызывать, даже если контроллер не найден (rtl8139_found() затем вернёт 0).
void rtl8139_init(void);

int rtl8139_found(void);

// 6-байтный MAC-адрес карты (валиден только если rtl8139_found()).
const uint8_t *rtl8139_get_mac(void);

// Отправить один Ethernet-кадр целиком (заголовок должен быть уже собран
// вызывающей стороной — см. kernel/net/eth.c). Блокирующая (ограниченный
// pit_wait_ms()-таймаут) — ждёт подтверждения передачи текущим слотом перед
// возвратом, так как все вызывающие в этом стеке и так уже находятся внутри
// синхронного send/poll-wait потока (ARP/ICMP/TCP). 0 = успех, -1 = ошибка.
int rtl8139_send(const void *frame, uint16_t len);

// Вызывается раз в тик PIT из net_poll(). Разбирает все доступные входящие
// кадры (ограничено фиксированным числом за один вызов) и передаёт каждый в
// eth_receive() (kernel/net/eth.c).
void rtl8139_poll(void);
