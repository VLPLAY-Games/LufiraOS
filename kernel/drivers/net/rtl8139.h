#pragma once

#include "lib/types.h"

/*
 * Драйвер RTL8139 (Realtek, PCI 0x10EC:0x8139) — порт-I/O BAR0 (не MMIO),
 * без scatter-gather на приём: NIC пишет кадры в один физически непрерывный
 * кольцевой буфер.
 *
 * Прерывания контроллера не используются (нет APIC/MSI/PCI capability list
 * в этом ядре) — rtl8139_poll() из net_poll() (раз в тик PIT, 100 Гц) сама
 * читает и подтверждает биты ISR; IMR всегда 0, линия INTx не взводится.
 */

// Инициализация: ищет контроллер через PCI, включает I/O + bus mastering,
// сбрасывает, настраивает приём/передачу, читает MAC-адрес. Безопасно
// вызывать, даже если контроллер не найден (rtl8139_found() затем вернёт 0).
void rtl8139_init(void);

int rtl8139_found(void);

// 6-байтный MAC-адрес карты (валиден только если rtl8139_found()).
const uint8_t *rtl8139_get_mac(void);

// Отправить один Ethernet-кадр (заголовок уже собран вызывающей стороной,
// см. kernel/net/eth.c). Блокирующая, с pit_wait_ms()-таймаутом — ждёт
// подтверждения передачи слотом. 0 = успех, -1 = ошибка.
int rtl8139_send(const void *frame, uint16_t len);

// Вызывается раз в тик PIT из net_poll(). Разбирает все доступные входящие
// кадры (ограничено фиксированным числом за один вызов) и передаёт каждый в
// eth_receive() (kernel/net/eth.c).
void rtl8139_poll(void);
