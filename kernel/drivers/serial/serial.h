#pragma once

#include "lib/types.h"

// Инициализация COM1 (0x3F8) — настраивает UART и определяет, реально ли
// за портом есть 16550 (loopback-тест), см. serial.c. Безопасно звать
// даже если порта нет вообще — serial_available() после этого просто
// вернёт 0, и все остальные функции станут no-op.
void serial_init(void);

int serial_available(void);

// Посимвольный блокирующий (опрос LSR, без прерываний — как и весь
// остальной polled-ввод/вывод в этом ядре) вывод. \n сам по себе НЕ
// досылает \r — вызывающий код (put_char() в console.c) уже передаёт оба
// символа отдельно, как настоящий терминал ожидает.
void serial_putc(char c);
void serial_puts(const char *s);

// Очередной принятый байт, если он уже есть, иначе -1 — тот же принцип
// "не блокируем ядро ожиданием", что у usb_poll()/net_poll().
int serial_try_getc(void);
