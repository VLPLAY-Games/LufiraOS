#pragma once

#include "lib/types.h"

// NVMe — v0.9, фаза 1, пункт 5: второй (после AHCI, см. ahci.h) способ
// добраться до реального диска на машинах без legacy SATA/IDE/AHCI вовсе —
// многие современные NVMe-накопители вообще не поддерживают AHCI-режим
// совместимости. Тот же опрос вместо прерываний, что и у AHCI/xHCI/
// RTL8139/AC'97 в этом ядре — но у NVMe это не просто "наш выбор", это
// даже естественнее: контроллер сигналит о завершении команды, просто
// переключая phase-бит в записи completion queue в ОБЫЧНОЙ памяти, так что
// опрос этого бита busy-wait-циклом — штатный механизм, а не замена
// прерыванию кустарным способом; parsing PCI capability list под MSI-X не
// нужен даже формально. Один контроллер, один namespace (NSID=1, первый),
// один admin queue pair (QID 0) + один I/O queue pair (QID 1), глубина
// каждой — 2 записи (здесь никогда не бывает больше одной команды "в
// полёте" одновременно — тот же стиль, что ahci_issue_command()). PRP —
// тот же физически непрерывный bounce-буфер на 128 КБ, что и у AHCI, плюс
// одна заранее заполненная (буфер неподвижен — список не нужно обновлять
// на каждый I/O) PRP-list страница под страницы 2..32.
//
// LBA namespace'а должен быть ровно 512 байт без metadata — иначе (как и
// AHCI на ATAPI-порту) контроллер просто остаётся недоступен, disk.c
// откатывается на следующий драйвер в цепочке.

int nvme_init(void);
int nvme_available(void);

int nvme_read_sectors(uint32_t lba, uint8_t sector_count, void *buffer);
int nvme_write_sectors(uint32_t lba, uint8_t sector_count, const void *buffer);
