#pragma once

// graphics2d.c — базовые 2D-примитивы поверх put_pixel() (console.c):
// v0.8-мост, пункт 1 ("графический примитив — есть только put_pixel").
// До этого файла единственный способ что-то нарисовать — put_pixel()
// по одному пикселю (так и сделаны put_char_graphic()/draw_cursor() и
// т.п. в console.c) — ни окну, ни даже простому прогресс-бару этого не
// хватит. Все функции здесь ожидают УЖЕ сконвертированный цвет (как и
// put_pixel()) — конвертировать RGB->BGR один раз на вызов, а не один
// раз на пиксель, тот же приём, что уже у console.c (current_color
// хранит результат convert_color(), не RGB напрямую).

#include "lib/types.h"

// Закрашивает прямоугольник [x, x+w) x [y, y+h) сплошным цветом.
// Отрицательные x/y и выход за границы экрана — клиппится молча (как и
// put_pixel() молча отбрасывает отдельные пиксели за экраном).
void gfx_fill_rect(int32_t x, int32_t y, uint32_t w, uint32_t h, uint32_t color);

// Рисует только контур прямоугольника (4 линии по 1px).
void gfx_draw_rect(int32_t x, int32_t y, uint32_t w, uint32_t h, uint32_t color);

// Отрезок между двумя произвольными точками (алгоритм Брезенхэма — целые
// операции, без чисел с плавающей точкой, которых в этом ядре нет).
void gfx_draw_line(int32_t x0, int32_t y0, int32_t x1, int32_t y1, uint32_t color);

// Копирует прямоугольник src_w x src_h из src (с построчным шагом
// src_stride ПИКСЕЛЕЙ — не обязательно равным src_w, тот же смысл, что
// "stride"/"pitch" в любом blit-API, позволяет брать подпрямоугольник
// из большего исходного буфера без копирования) в кадровый буфер начиная
// с (dst_x, dst_y). Пиксели src УЖЕ в формате кадрового буфера (как и
// цвет у fill_rect/draw_line выше) — blit их не конвертирует, только
// копирует. Клиппится по экрану с обеих сторон.
void gfx_blit(int32_t dst_x, int32_t dst_y, const uint32_t *src,
               uint32_t src_w, uint32_t src_h, uint32_t src_stride);
