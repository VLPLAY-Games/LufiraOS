#pragma once

#include "lib/types.h"

/*
 * Общий входной слой: и PS/2, и USB HID клавиатура/мышь сообщают о
 * событиях сюда, а не напрямую в shell/консоль. Это единственная точка,
 * которая знает, что делать с нажатием клавиши или движением мыши,
 * независимо от того, с какой шины оно пришло.
 */

// Обрабатывает уже декодированную клавишу (ASCII-символ либо KEY_* из
// keyboard.h). key == 0 игнорируется (нет символа для этого скан-кода).
void input_keyboard_event(int key);

// dx/dy — относительное смещение с последнего события (положительное dy
// означает движение вниз, как и положено экранным координатам); buttons —
// битовая маска нажатых кнопок (бит 0 = левая, 1 = правая, 2 = средняя).
void input_mouse_event(int dx, int dy, uint8_t buttons);

int input_mouse_get_x(void);
int input_mouse_get_y(void);
uint8_t input_mouse_get_buttons(void);

// Кольцевой буфер сырых байт клавиатуры для БЛОКИРУЮЩЕГО console_read()
// (vfs.c) — v0.7 план, этап 5, под-этап 6. Параллельный путь вдобавок к
// существующему прямому вызову shell_handle_*() из input_keyboard_event()
// ниже: тот остаётся нетронутым (кернел-нативный шелл продолжает работать
// как раньше), пока будущий shell.elf не заменит его целиком. Байты — те
// же коды, что уже определены в keyboard.h (KEY_LEFT_ARROW=0x01 и т.д.),
// свой формат, не ANSI — программам, читающим /dev/console, ничего
// внешнего эмулировать не нужно. KEY_CTRL_C сюда никогда не попадает —
// станет настоящим SIGINT (следующий под-этап), а не байтом в потоке.
//
// Блокирующее чтение: если буфер пуст, вызывающий процесс переводится в
// PROCESS_BLOCKED и уступает CPU (schedule()) — тем же приёмом, что уже
// использует pipe_read() (vfs.c), но, в отличие от него, console_input_push()
// ниже ЯВНО будит ожидающего писателя обратно в PROCESS_READY, когда
// приходит байт (у pipe такого пробуждения нет вообще — см. отдельно
// заведённую задачу на этот счёт).
int console_input_read(uint8_t *out, int max);
