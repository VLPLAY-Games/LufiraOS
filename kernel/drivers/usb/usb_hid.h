#pragma once

#include "lib/types.h"

/*
 * Декодер boot-протокола USB HID (без парсинга HID Report Descriptor —
 * фиксированный формат отчёта, который понимает даже BIOS). Не знает
 * ничего о конкретном хост-контроллере (UHCI/OHCI) — только о байтах
 * самого отчёта, которые ему передаёт HCD-драйвер после каждой
 * завершённой interrupt-передачи с endpoint'а клавиатуры.
 */

// report — 8 байт boot-отчёта клавиатуры: [0]=модификаторы (Ctrl/Shift/
// Alt/GUI, лево+право), [1]=зарезервировано, [2..7]=до 6 одновременно
// нажатых usage-кодов (0 = пусто, 1 = ошибка переполнения — оба
// игнорируются). Новые (не бывшие в предыдущем отчёте) usage-коды
// декодируются в ASCII/KEY_* и уходят в input_keyboard_event().
void usb_hid_keyboard_report(const uint8_t report[8]);
