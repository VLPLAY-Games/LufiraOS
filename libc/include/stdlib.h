// stdlib.h — минимальный набор: malloc/free (см. libc/src/malloc.c) и
// exit(). Никаких calloc/realloc в этой версии: calloc() не свободен от
// сложности realloc(), как только учитываешь, что переиспользуемый
// (не свежий, не из только что смапленной арены) блок может содержать
// старые данные — то есть настоящий calloc() всё равно нуждается в memset,
// так что "тривиальной" экономии не получается, а решили брать только то,
// что действительно тривиально.
#pragma once

#include <stddef.h>

void *malloc(size_t size);
void free(void *ptr);

// Оборачивает SYS_EXIT — не возвращается. Никаких atexit()-хендлеров или
// сброса stdio-буферов: printf() делает write() сразу при каждом вызове,
// сбрасывать нечего.
__attribute__((noreturn)) void exit(int code);
